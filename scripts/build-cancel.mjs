// Builds src/catalog/cancel.data.ts from docs/research/cancel-guides-2026-11.json:
// each top service's official cancel page (or help article) and 3 short steps.
// Official sources only. Rows with no confidence are left out (they get the
// generic steps). Usage: node scripts/build-cancel.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const IN = join(root, 'docs/research/cancel-guides-2026-11.json');
const OUT = join(root, 'src/catalog/cancel.data.ts');
const APPLE = 'https://apps.apple.com/account/subscriptions';

const { checkedOn, services } = JSON.parse(readFileSync(IN, 'utf8'));
const rows = {};
for (const s of services) {
  if (s.confidence === 'none' || !s.steps?.length) continue;
  const row = { steps: s.steps.map((x) => x.replace(/\.$/, '')) };
  if (s.url === APPLE) row.apple = true;
  else if (s.url) row.url = s.url;
  else if (s.helpUrl) row.helpUrl = s.helpUrl;
  if (s.appleNote) row.appleNote = true;
  rows[s.id] = row;
}
writeFileSync(
  OUT,
  `// Generated by scripts/build-cancel.mjs from docs/research/cancel-guides-2026-11.json.
// Official cancel pages and steps, checked ${checkedOn}. Don't edit by hand.

export type CancelGuide = {
  /** The service's own cancel or manage page. */
  url?: string;
  /** Only a help article (no direct page). */
  helpUrl?: string;
  /** Apple's own service: cancel in Apple's subscriptions page. */
  apple?: boolean;
  /** Could also be billed through Apple (then it's in iPhone Settings). */
  appleNote?: boolean;
  steps: string[];
};

export const CANCEL_CHECKED = '${checkedOn}';

export const CANCEL_GUIDES: Record<string, CancelGuide> = ${JSON.stringify(rows, null, 2)};
`,
);
console.log(`${Object.keys(rows).length} guides → ${OUT}`);
