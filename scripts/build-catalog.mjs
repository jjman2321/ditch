// Builds src/catalog/services.data.ts and src/catalog/logos.ts from
// scripts/catalog/catalog.txt (+ top100.txt for popularity).
// Usage: npm run catalog   (re-run whenever the catalog or assets/logos change)
//
// A service gets a logo only when assets/logos/<id>.png exists
// (fetched by scripts/catalog/fetch-logos.py); otherwise the app shows its
// brand-colour monogram tile.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG = join(root, 'scripts/catalog/catalog.txt');
const TOP = join(root, 'scripts/catalog/top100.txt');
const COUNTRIES = ['US', 'GB', 'CA', 'AU', 'IE', 'NZ', 'DE', 'NL', 'FR', 'IT', 'ES', 'IN'];
const CATEGORIES = {
  ST: 'Streaming',
  MU: 'Music & audio',
  AI: 'AI',
  PR: 'Productivity',
  CS: 'Cloud & security',
  SH: 'Shopping & food',
  HF: 'Health & fitness',
  DA: 'Dating',
  SO: 'Social',
  NE: 'News & reading',
  GA: 'Gaming',
  LE: 'Learning',
};
const POPULAR_FLAG = 20; // the top N get `popular: true` (the editor's first suggestions)

/** Split on | but not inside (...), so seller regexes can use alternation. */
function split(line) {
  const parts = [];
  let cur = '';
  let depth = 0;
  for (const ch of line) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === '|' && depth === 0) {
      parts.push(cur);
      cur = '';
    } else cur += ch;
  }
  parts.push(cur);
  return parts;
}

/** WCAG relative luminance of a #RRGGBB colour. */
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const lines = (file) =>
  readFileSync(file, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));

const top = lines(TOP);
const rank = new Map(top.map((id, i) => [id, i + 1]));

const services = lines(CATALOG).map((line) => {
  const p = split(line);
  if (p.length !== 11 && p.length !== 12) throw new Error(`bad catalog line (${p.length} columns): ${line}`);
  const [id, name, cat, color, mono, cycle, countries, aliases] = p;
  const flags = p[11] ? p[11].split(',') : [];
  if (!CATEGORIES[cat]) throw new Error(`${id}: unknown category ${cat}`);
  const availableIn = countries === '-' ? undefined : countries.split(',');
  for (const c of availableIn ?? []) if (!COUNTRIES.includes(c)) throw new Error(`${id}: unknown country ${c}`);
  const svc = {
    id,
    name,
    category: CATEGORIES[cat],
    color,
    mono,
    cycle: { m: 'monthly', y: 'yearly' }[cycle],
  };
  if (!svc.cycle) throw new Error(`${id}: bad cycle ${cycle}`);
  if (availableIn) svc.availableIn = availableIn;
  const al = aliases
    .split(',')
    .map((a) => a.trim())
    .filter(Boolean);
  if (al.length) svc.aliases = al;
  if (flags.includes('apple')) svc.billedVia = 'apple';
  if (rank.has(id)) svc.rank = rank.get(id);
  if (rank.get(id) <= POPULAR_FLAG) svc.popular = true;
  if (luminance(color) > 0.45) svc.ink = '#16140F'; // dark letters on light tiles
  return svc;
});

const ids = new Set();
for (const s of services) {
  if (ids.has(s.id)) throw new Error(`duplicate id ${s.id}`);
  ids.add(s.id);
}
for (const id of top) if (!ids.has(id)) throw new Error(`top100.txt: ${id} is not in the catalog`);
if (top.length !== new Set(top).size) throw new Error('top100.txt has duplicates');

const counts = Object.values(CATEGORIES).map((c) => `${c} ${services.filter((s) => s.category === c).length}`);

writeFileSync(
  join(root, 'src/catalog/services.data.ts'),
  `// GENERATED by scripts/build-catalog.mjs from scripts/catalog/catalog.txt.
// Do not edit by hand: change catalog.txt (or top100.txt) and run \`npm run catalog\`.
// ${services.length} services: ${counts.join(', ')}.

import type { CatalogService } from './services';

export const SERVICE_ROWS: CatalogService[] = ${JSON.stringify(services, null, 2)};

/** Most popular first (scripts/catalog/top100.txt). */
export const TOP_IDS: string[] = ${JSON.stringify(top)};
`,
);

const withLogo = services.filter((s) => existsSync(join(root, 'assets/logos', `${s.id}.png`)));
writeFileSync(
  join(root, 'src/catalog/logos.ts'),
  `// GENERATED by scripts/build-catalog.mjs: one entry per assets/logos/<id>.png.
// Real App Store icons for catalog services, bundled (never fetched at runtime).
// Used to name the service the user pays for (nominative use).
// ${withLogo.length} of ${services.length} services have a logo; the rest show a monogram tile.
export const LOGOS: Record<string, number> = {
${withLogo.map((s) => `  '${s.id}': require('../../assets/logos/${s.id}.png'),`).join('\n')}
};
`,
);
console.log(`Wrote ${services.length} services (${withLogo.length} with logos).`);
