// Builds src/catalog/fx.data.ts: a snapshot of exchange rates that ships in
// the app, so the "≈ in all" line works offline from the first launch.
// The app refreshes them itself at most once a day, and only for people
// with 2+ currencies on their list (src/services/fx.ts).
// Usage: npm run fx   (re-run before each release)
// Rates by Exchange Rate API (https://www.exchangerate-api.com), free, no key.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src/catalog/fx.data.ts');

const res = await fetch('https://open.er-api.com/v6/latest/USD');
const data = await res.json();
if (data.result !== 'success' || data.base_code !== 'USD') throw new Error('Unexpected response from open.er-api.com');
const date = new Date(data.time_last_update_unix * 1000).toISOString().slice(0, 10);
const rates = Object.fromEntries(
  Object.entries(data.rates)
    .filter(([k, v]) => /^[A-Z]{3}$/.test(k) && typeof v === 'number' && v > 0)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => [k, Number(v.toPrecision(7))]),
);

writeFileSync(
  OUT,
  `// Generated by scripts/build-fx.mjs on ${date}. Do not edit by hand.\n` +
    `// Rates by Exchange Rate API (exchangerate-api.com): units of each currency per 1 US dollar.\n\n` +
    `import type { Rates } from '@/domain/fx';\n\n` +
    `export const BUNDLED_RATES: Rates = ${JSON.stringify({ date, rates }, null, 2)};\n`,
);
console.log(`fx.data.ts: ${Object.keys(rates).length} currencies, rates from ${date}`);
