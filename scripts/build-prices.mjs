// Builds src/catalog/prices.data.ts from the checked price research.
// Usage: npm run prices   (re-run whenever docs/research/prices-*.json changes)
//
// Only rows with status "verified" ship (DECISIONS #17: never show a price
// we haven't checked on the official page). Pass --include-partial to also
// ship "partial" rows.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'docs/research/prices-2026-11.json');
const OUT = join(root, 'src/catalog/prices.data.ts');
const keep = new Set(['verified', ...(process.argv.includes('--include-partial') ? ['partial'] : [])]);

const data = JSON.parse(readFileSync(SRC, 'utf8'));
const rows = data.prices
  .filter((r) => keep.has(r.status))
  .map((r) => ({
    serviceId: r.serviceId,
    country: r.country,
    currency: r.currency,
    status: r.status,
    plans: r.plans.map((p) => ({ id: p.id, name: p.name, amountMinor: p.amountMinor, cycle: p.cycle, ...(p.default ? { default: true } : {}) })),
    source: r.source,
    checked: r.checked,
    ...(r.note ? { note: r.note } : {}),
  }))
  .sort((a, b) => (a.serviceId + a.country).localeCompare(b.serviceId + b.country));

const out = `// GENERATED by scripts/build-prices.mjs from docs/research/prices-2026-11.json.
// Do not edit by hand: change the research file and run \`npm run prices\`.
// ${rows.length} rows (statuses: ${[...keep].join(', ')}), checked ${data.about.checked}.

import type { CountryPrice } from './prices';

export const PRICE_ROWS: CountryPrice[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(OUT, out);
console.log(`Wrote ${rows.length} rows to ${OUT}`);
