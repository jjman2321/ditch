// Builds src/catalog/rights.data.ts from the newest docs/research/rights-*.json.
// Usage: npm run rights   (re-run whenever that file changes)
// The website copies the same file in web/scripts/sync-data.mjs.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RESEARCH = join(root, 'docs/research');
const file = readdirSync(RESEARCH).filter((n) => n.startsWith('rights-') && n.endsWith('.json')).sort().pop();
const data = JSON.parse(readFileSync(join(RESEARCH, file), 'utf8'));
const { about, countries, regions } = data;

const out = `// GENERATED by scripts/build-rights.mjs from docs/research/${file}.
// Do not edit by hand: change the research file and run \`npm run rights\`.

import type { RightsData } from './rights';

export const RIGHTS: RightsData = ${JSON.stringify({ checked: about.checked, disclaimer: about.disclaimer, countries, regions }, null, 2)};
`;
writeFileSync(join(root, 'src/catalog/rights.data.ts'), out);
console.log(`Wrote ${regions.length} regions for ${Object.keys(countries).length} countries`);
