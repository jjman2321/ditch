-- One "api" Edge Function serves every route now (supabase/functions/api): point the hourly cleanup at it.
select cron.unschedule('bank-cleanup-hourly');
select cron.schedule(
  'bank-cleanup-hourly',
  '7 * * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets where name = 'project_url') || '/functions/v1/api/bank-cleanup',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'cron_secret')
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 120000
  );
  $$
);
